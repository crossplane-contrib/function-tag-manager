// Package filters determines whether resources support tags
package filters

import (
	"regexp"

	"github.com/crossplane/crossplane-runtime/v2/pkg/errors"
)

// validField matches a single, unquoted field name. A dotted or bracketed value
// would be treated by the fieldpath library as a nested path, and anything else
// can't be safely written into generated Go source.
var validField = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)

// ValidateField returns an error if field isn't usable as the name of a single
// spec.forProvider or status.atProvider field.
func ValidateField(field string) error {
	if !validField.MatchString(field) {
		return errors.Errorf("invalid field name %q: must be a single field name, for example \"tags\"", field)
	}

	return nil
}

// TagFields names the fields that hold a resource's tags.
type TagFields struct {
	// Spec is the name of the spec.forProvider field that holds the tags the
	// function manages.
	Spec string
	// Observed is the name of the status.atProvider field that holds the tags
	// that exist on the external resource, including any set outside Crossplane.
	Observed string
}

// ResourceFilter maps a resource's GroupKind to the fields that hold its tags.
// Resources that don't support tags are not present.
type ResourceFilter map[string]TagFields

// ProviderFilter indicates which of a provider's resources support tags,
// and the names of the fields that hold them.
type ProviderFilter struct {
	// Field is the name of the spec.forProvider field that holds tags.
	Field string
	// ObservedField is the name of the status.atProvider field that holds the
	// tags that exist on the external resource. It defaults to Field.
	ObservedField string
	// Resources maps a GroupKind to whether it supports Field.
	Resources map[string]bool
}

// NewProviderFilter returns a ProviderFilter for the given field. The observed
// field is the same as the field unless overridden with WithObservedField.
func NewProviderFilter(field string, resources map[string]bool) ProviderFilter {
	return ProviderFilter{Field: field, ObservedField: field, Resources: resources}
}

// WithObservedField returns a copy of the ProviderFilter that reads existing
// tags from status.atProvider.<observed>. Use it when a provider reports the
// tags that exist on the external resource somewhere other than the field it
// accepts them in, for example Terraform-based GCP resources, where labels set
// outside Crossplane appear in effectiveLabels rather than labels.
func (pf ProviderFilter) WithObservedField(observed string) ProviderFilter {
	pf.ObservedField = observed
	return pf
}

// NewResourceFilter returns a map of resources that support tags.
// These values were generated by querying Provider CRDs for the
// spec.forProvider field that holds tags: `tags` for AWS and Azure.
func NewResourceFilter() ResourceFilter {
	return newResourceFilter(NewAWSResourceFilter(), NewAzureResourceFilter())
}

// newResourceFilter merges the resources that support tags in each provider.
// A provider whose Field or ObservedField isn't a valid field name is skipped,
// because managing it would write tags to a path that doesn't exist. An empty
// ObservedField defaults to Field.
func newResourceFilter(providers ...ProviderFilter) ResourceFilter {
	all := make(ResourceFilter)

	for _, pf := range providers {
		observed := pf.ObservedField
		if observed == "" {
			observed = pf.Field
		}

		if ValidateField(pf.Field) != nil || ValidateField(observed) != nil {
			continue
		}

		for groupKind, supported := range pf.Resources {
			if supported {
				all[groupKind] = TagFields{Spec: pf.Field, Observed: observed}
			}
		}
	}

	return all
}
